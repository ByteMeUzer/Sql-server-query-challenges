

USE HARD_LEVEL_DB


SELECT * FROM INFORMATION_SCHEMA.TABLES ORDER BY TABLE_TYPE ASC



WITH CTE AS 
(
SELECT *,
DENSE_RANK() OVER(ORDER BY SALARY DESC) DR
FROM EMPLOYEES WITH(NOLOCK)
)
SELECT DR, FNAME, LNAME, SALARY, DEPT_NAME FROM CTE C
INNER JOIN DEPARTMENTS D ON C.DEPT_ID = D.DEPT_ID
WHERE DR <= 3
ORDER BY SALARY DESC

SELECT GETDATE()


SELECT E2.FNAME, E2.LNAME, E2.HIRE_DATE, E1.FNAME
FROM EMPLOYEES E1 WITH(NOLOCK)
JOIN EMPLOYEES E2 WITH(NOLOCK) ON E1.MANAGER_ID = E2.EMP_ID
WHERE E1.HIRE_DATE < E2.HIRE_DATE



WITH CTE AS 
(
	SELECT E.FNAME, E.LNAME, SH.OLD_SALARY, SH.NEW_SALARY,
	ROW_NUMBER() OVER(PARTITION BY SALARY ORDER BY  NEW_SALARY DESC)  RN
	FROM EMPLOYEES E WITH(NOLOCK)
	INNER JOIN SALARY_HISTORY SH ON E.EMP_ID = SH.EMP_ID
),

HIKE AS (
SELECT FNAME, LNAME,
((NEW_SALARY-OLD_SALARY) * 100 / OLD_SALARY) AS SALARY_HIKE FROM CTE
WHERE RN = 1
)
SELECT * FROM HIKE
WHERE SALARY_HIKE > 50


WITH CTE AS (
	SELECT E.FNAME, E.LNAME, E.HIRE_DATE, D.DEPT_NAME,
	RANK() OVER(PARTITION BY DEPT_NAME  ORDER BY HIRE_DATE ASC) OLD_RANK,
	RANK() OVER(PARTITION BY DEPT_NAME  ORDER BY HIRE_DATE DESC) NEW_RANK
	FROM EMPLOYEES E WITH(NOLOCK)
	INNER JOIN DEPARTMENTS D ON E.DEPT_ID = D.DEPT_ID
	)
SELECT FNAME, LNAME, DEPT_NAME,HIRE_DATE,
CASE 
        WHEN OLD_RANK = 1 AND NEW_RANK = 1 THEN 'OLD & NEW DATE' -- AGAR DEPARTMENT MEIN SIRF 1 EMPLOYEE HO
        WHEN OLD_RANK = 1 THEN 'OLD DATE'
        WHEN NEW_RANK = 1 THEN 'NEW DATE'
    END AS DATE_STATUS
   FROM CTE
WHERE OLD_RANK = 1 OR NEW_RANK = 1


SELECT P.PROJECT_NAME, SUM(E.SALARY) AS TOTAL_SALARY, P.BUDGET
FROM EMPLOYEES E WITH(NOLOCK)
INNER JOIN EMPLOYEE_PROJECTS EP WITH(NOLOCK) ON E.EMP_ID = EP.EMP_ID
INNER JOIN PROJECTS P WITH(NOLOCK) ON EP.PROJECT_ID = P.PROJECT_ID
GROUP BY P.PROJECT_NAME, P.BUDGET
HAVING SUM(E.SALARY) > (P.BUDGET * 0.10)


