WITH CTE AS 
(
	SELECT CITY, AVG(SALARY) AS AVG_SALARY FROM EMPLOYEES WITH(NOLOCK)
	GROUP BY CITY
),
SEC_CTE AS 
(SELECT AVG(SALARY) AS COMP_AVG  FROM EMPLOYEES WITH(NOLOCK))

SELECT C.CITY, C.AVG_SALARY
FROM CTE C
CROSS JOIN SEC_CTE COMP
WHERE C.AVG_SALARY > COMP.COMP_AVG
order by c.AVG_SALARY desc



WITH CTE AS 
(
	SELECT TOP 1 * FROM EMPLOYEES WITH(NOLOCK)
	WHERE DEPARTMENT = 'IT'
	ORDER BY SALARY DESC
),
CTE_TWO AS 
(	
	SELECT TOP 1 * FROM EMPLOYEES WITH(NOLOCK)
	WHERE DEPARTMENT = 'SALES'
	ORDER BY SALARY DESC
)

SELECT * FROM CTE C
CROSS JOIN CTE_TWO CT
WHERE C.SALARY > CT.SALARY OR C.SALARY < CT.SALARY


