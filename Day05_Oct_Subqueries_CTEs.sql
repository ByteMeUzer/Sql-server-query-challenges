SELECT FNAME, DEPARTMENT, JOB_TITLE, SALARY
FROM EMPLOYEES E1 WITH(NOLOCK)
WHERE SALARY > (SELECT AVG(SALARY) FROM EMPLOYEES E2 WITH(NOLOCK) 
WHERE E1.DEPARTMENT = E2.DEPARTMENT)
ORDER BY DEPARTMENT , SALARY ASC



SELECT FNAME, DEPARTMENT, JOB_TITLE, SALARY
FROM EMPLOYEES E1 WITH(NOLOCK)
WHERE SALARY > (SELECT AVG(SALARY) as avg_dep_sal FROM EMPLOYEES E2 WITH(NOLOCK) 
WHERE E1.DEPARTMENT = E2.DEPARTMENT)
ORDER BY DEPARTMENT , SALARY ASC



SELECT FNAME, DEPARTMENT, JOB_TITLE, SALARY,
(SELECT round(AVG(SALARY),2) AS AVG_DEP_SAL FROM EMPLOYEES E2 WITH(NOLOCK) 
WHERE E1.DEPARTMENT = E2.DEPARTMENT) AS DEPT_MAX_SALARY
FROM EMPLOYEES E1 WITH(NOLOCK)
order by department, salary, DEPT_MAX_SALARY asc



SELECT FNAME, DEPARTMENT, JOB_TITLE, SALARY FROM EMPLOYEES WITH(NOLOCK)
WHERE CITY = (SELECT TOP 1 CITY FROM 
(SELECT AVG(SALARY) AS AVG_SALARY , CITY FROM EMPLOYEES WITH(NOLOCK) GROUP BY CITY) AS NEW_COLUMN
ORDER BY AVG_SALARY DESC)



SELECT FNAME, LNAME, DEPARTMENT, SALARY  
FROM  EMPLOYEES E1  WITH(NOLOCK) 
WHERE  EXISTS  (SELECT  SALARY FROM EMPLOYEES E2 WITH(NOLOCK) 
				WHERE E1.DEPARTMENT = E2.DEPARTMENT AND E2.SALARY > 100000)
ORDER BY DEPARTMENT, SALARY ASC



SELECT FNAME, LNAME, DEPARTMENT, SALARY  
FROM  EMPLOYEES E1  WITH(NOLOCK) 
WHERE NOT  EXISTS  (SELECT 1  SALARY FROM EMPLOYEES E2 WITH(NOLOCK) 
				WHERE E1.DEPARTMENT <> E2.DEPARTMENT AND E2.fname = E1.fname)
ORDER BY DEPARTMENT, SALARY ASC



