WITH CTE AS 
(
	SELECT *,
	DENSE_RANK() OVER(PARTITION BY DEPARTMENT ORDER BY SALARY DESC) DR
	FROM EMPLOYEES WITH(NOLOCK)
)
SELECT DEPARTMENT, SALARY FROM CTE 
WHERE DR = 2
ORDER BY SALARY DESC


