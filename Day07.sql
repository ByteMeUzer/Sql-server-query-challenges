SELECT 
AVG(SALARY) OVER(),
 (SALARY - AVG(SALARY) OVER()) * 100.0 / AVG(SALARY) OVER() AS SALARY_PERCENTAGE_VARIANCE, *
 FROM EMPLOYEES WITH(NOLOCK)
 


--TOP 3 CITIES JINKA AVERAGE SALARY SABSE ZYADA HAI, UNKE ANDAR KAUN SA DEPARTMENT SABSE ZYADA AVERAGE DE RAHA HAI?
 WITH CITY_AVG AS (
    -- STEP 1: HAR CITY KA AVERAGE SALARY NIKAL KAR TOP 3 CITIES FILTER KARNA
    SELECT 
        CITY,
        AVG(SALARY) AS AVG_CITY_SALARY,
        DENSE_RANK() OVER (ORDER BY AVG(SALARY) DESC) AS CITY_RANK
    FROM EMPLOYEES
    GROUP BY CITY
),
TOP_3_CITIES AS (
    -- SIRF TOP 3 CITIES KO SELECT KAR RAHE HAIN
    SELECT CITY 
    FROM CITY_AVG 
    WHERE CITY_RANK <= 3
),
DEPARTMENT_AVG AS (
    -- STEP 2: TOP 3 CITIES KE ANDAR DEPARTMENT WISE AVERAGE SALARY NIKALNA
    SELECT 
        E.CITY,
        E.DEPARTMENT,
        AVG(E.SALARY) AS AVG_DEPT_SALARY,
        ROW_NUMBER() OVER (PARTITION BY E.CITY ORDER BY AVG(E.SALARY) DESC) AS DEPT_RANK
    FROM EMPLOYEES E
    INNER JOIN TOP_3_CITIES T ON E.CITY = T.CITY
    GROUP BY E.CITY, E.DEPARTMENT
)
-- STEP 3: HAR CITY SE SIRF HIGHEST AVERAGE WAALA DEPARTMENT NIKALNA
SELECT 
    CITY,
    DEPARTMENT,
    ROUND(AVG_DEPT_SALARY, 2) AS HIGHEST_AVG_SALARY
FROM DEPARTMENT_AVG
WHERE DEPT_RANK = 1;

 
