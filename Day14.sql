USE PRACTICE

SELECT * FROM EMPLOYEES WITH(NOLOCK) 
ORDER BY EMPID DESC


WITH CTE AS 
(
	SELECT EMPID, FNAME, DEPARTMENT, HIRE_DATE,
	DENSE_RANK() OVER(PARTITION BY DEPARTMENT ORDER BY HIRE_DATE ASC) AS DR
	FROM EMPLOYEES WITH(NOLOCK)
)
SELECT * FROM CTE 
WHERE DR = 3


SELECT FNAME, DEPARTMENT, SALARY, 
LAG(SALARY) OVER(PARTITION BY DEPARTMENT ORDER BY HIRE_DATE ASC)
FROM EMPLOYEES WITH(NOLOCK)



SELECT CITY, FNAME, SALARY FROM EMPLOYEES E1 WITH(NOLOCK)
WHERE SALARY > (SELECT AVG(SALARY) AS AVG_CITY_SALARY FROM EMPLOYEES E2 WITH(NOLOCK) WHERE E1.CITY = E2.CITY)
ORDER BY CITY, SALARY DESC




WITH CTE AS
(
    SELECT FNAME, SALARY, DEPARTMENT, 
           SUM(SALARY) OVER(PARTITION BY DEPARTMENT) AS TOTAL,
           NTILE(3) OVER (ORDER BY SALARY DESC) AS BUCKET
    FROM EMPLOYEES
)
SELECT *,
CASE 
    WHEN BUCKET = 1 THEN 'HIGH'
    WHEN BUCKET = 2 THEN 'MEDIUM'
    ELSE 'LOW'
END CATEGORY
FROM CTE


SELECT 
    department,
    MAX(salary) AS max_salary,
    MIN(salary) AS min_salary,
    ROUND(MAX(salary) / MIN(salary), 2) AS ratio
FROM 
    employees
GROUP BY 
    department
HAVING 
    MAX(salary) > 2 * MIN(salary);
